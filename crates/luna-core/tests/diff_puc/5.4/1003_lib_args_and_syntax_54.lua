-- Argument checks, lexer and parser messages as a script named
-- "@user_script" sees them (Redis's chunk name). A missing argument is
-- "no value" (lua_type == LUA_TNONE), a nil one is "nil". Lexer and
-- parser messages name the token as each dialect's luaX_token2str /
-- txtToken does ('<eof>' and '<name>' quoted in 5.1 and from 5.3 on,
-- bare in 5.2). In 5.1 goto is an ordinary name.
local load = loadstring or load
local function run(src)
  local f, m = load(src, "@user_script")
  if not f then print("compile", m) return end
  print("run", select(2, pcall(f)))
end
local function call(name, ...)
  local ok, f = pcall(load("return " .. name))
  if ok and f then print(name, select('#', ...), select(2, pcall(f, ...))) end
end
