-- string.rep and string.sub check their arguments in separate statements;
-- functions that pass several checks as the arguments of one C call
-- (math.fmod, bit32.lshift, package.searchpath, ...) are left out, since
-- which one fails first depends on the C compiler that built PUC
for _, n in ipairs({"string.rep", "string.sub", "string.byte", "table.concat"}) do
  call(n)
  call(n, nil)
  call(n, "x", nil)
  call(n, nil, "x")
end
